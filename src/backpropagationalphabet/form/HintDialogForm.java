    /** Add explanatory content outside the section generated by NetBeans. */
    private void configureHintContent() {
        jPanel1.setLayout(new BorderLayout());
        JTextArea hintText = new JTextArea(
                "PETUNJUK PENGGUNAAN\n\n"
                + "Aplikasi ini mengenali pola huruf kapital A-Z menggunakan jaringan saraf tiruan "
                + "Backpropagation. Tiap pola terdiri dari 7 kolom x 9 baris (63 kotak).\n\n"
                + "Training memakai 11 variasi sintetis untuk setiap huruf (pola asli, pergeseran, "
                + "perubahan skala, dan kemiringan ringan). Variasi ini membantu menangani posisi "
                + "dan ukuran berbeda, tetapi bukan pengganti contoh tulisan tangan nyata.\n\n"
                + "PENGUJIAN\n"
                + "1. Klik-tahan lalu seret pada grid untuk mewarnai banyak kotak sekaligus. Kotak pertama menentukan warna goresan; kotak lain yang dilewati mengikuti warna itu.\n"
                + "2. Gunakan tombol huruf di samping grid untuk memuat pola contoh.\n"
                + "3. Klik TEST untuk meminta jaringan menebak huruf. Jaringan harus dilatih "
                + "terlebih dahulu; hasilnya adalah target alfabet yang paling dekat dengan output.\n\n"
                + "TRAINING\n"
                + "1. Buka tab Training dan isi Alpha (learning rate), Epoch (batas maksimum putaran "
                + "seluruh pola training), dan Tolerance (batas MSE untuk berhenti lebih awal). "
                + "Nilai awal form: Alpha 0.1, Epoch 1000, Tolerance 0.1.\n"
                + "2. Klik Train. Proses berjalan di latar belakang dan log MSE tiap epoch akan "
                + "muncul sambil training berjalan. Training berhenti saat MSE <= Tolerance atau "
                + "saat mencapai batas Epoch. Klik Stop untuk berhenti setelah epoch berjalan selesai.\n"
                + "3. Setelah training selesai, kembali ke tab Testing dan uji pola.\n\n"
                + "Catatan: bobot diinisialisasi secara acak saat training dimulai, sehingga hasil "
                + "dapat sedikit berbeda tiap training. Bobot tidak disimpan setelah aplikasi ditutup.\n"
                + "Tolerance 0 menonaktifkan penghentian lebih awal kecuali MSE tepat 0.");
        hintText.setRows(18);
        hintText.setColumns(58);
        hintText.setEditable(false);
        hintText.setLineWrap(true);
        hintText.setWrapStyleWord(true);
        hintText.setCaretPosition(0);
        jPanel1.add(new JScrollPane(hintText), BorderLayout.CENTER);
        jLabel1.setText("Credits: Bayu Irfan — implementasi aplikasi dan pola alfabet training.");
        pack();
    }

